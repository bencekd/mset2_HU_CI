    def set_exog_inv(self, investment_base):
        # columns to be passed on
        columns_ = ['REG_imp','PROD_COMM',self.YEAR,'Type']

        try:
            inv_exog = pd.read_excel(self.scenario_file, sheet_name='Investment by', skiprows=14)
            inv_exog = inv_exog[['Country ISO*','Sector investing code*',self.YEAR,'Type*']]
            inv_exog.columns = columns_
        except (ValueError, KeyError):
            inv_exog = pd.DataFrame(columns=columns_)

        # read in power investment, if any
        try:
            power_inv_exog = pd.read_excel(self.scenario_file, sheet_name='Power investment', skiprows=13)
            power_inv_exog = power_inv_exog[['Country ISO*','Sector investing code*', self.YEAR,'Type*']]
            power_inv_exog.columns = columns_
        except ValueError:
            power_inv_exog = pd.DataFrame(columns=columns_)

        inv_exog = pd.concat([inv_exog, power_inv_exog], axis=0)    

        inv_exog = inv_exog.rename(columns={self.YEAR:'Value'})

        # add index before resolving
        inv_exog['Line'] = np.arange(len(inv_exog)).tolist()

        inv_exog = resolve_comma(inv_exog, "REG_imp")
        inv_exog = resolve_all(inv_exog, "REG_imp", self.REGIONS['Region_acronyms'].to_list())

        inv_exog = resolve_comma(inv_exog, "PROD_COMM")
        inv_exog = resolve_hyphen(inv_exog, "PROD_COMM")
        inv_exog = resolve_all(inv_exog, "PROD_COMM", list(self.P_IDS))

        # ? Scenario.fd_exog structure is the following:
        # ? REG_imp | PROD_COMM | Value | Type
        # ? Type can be: abs-b [absolute-proportional-base] | abs [absolute-proportional-new] 
        # ? | rel [relative] | rel-b [relative to baseline]
        # ? if absolute is used with multiple sectors / countries
        # ? then numbers are proportionally spread out
        # ? proportionality is either to the base [abs-b] or to the current FD vector [abs]
        # TODO: abs is to be implemented later [with annualized model version]
        # TODO: rel is to be implemented later [with annualized model version]
        # TODO: rel-b is to be implemented later !! - we don't have investment baseline BY 
        # TODO: investing sector

        # ? abs-b: abs-b is absolute impact based on Y0
        # ? if multiple specified from something, then spread out proportionally

        df_absb = inv_exog[inv_exog['Type'].str.contains('abs-b')].copy()
        df_absb['PROD_COMM'] = df_absb['PROD_COMM'].astype(int)
        df_absb = df_absb.merge(investment_base, how='left', on=['REG_imp','PROD_COMM'])
        df_absb['dk_base'] = df_absb['dk_base'].fillna(0)
        # calculate share by line
        # ! if the line's dk_base sum is zero (e.g. sectors with an externally
        # ! given investment pathway and zeroed base investment) spread the
        # ! value equally across the line's cells instead of dropping it (0/0)
        line_base = df_absb.groupby(['Line'])['dk_base'].transform('sum')
        df_absb['share'] = np.where(line_base > 0,
                                    df_absb['dk_base'] / line_base,
                                    1 / df_absb.groupby(['Line'])['Line'].transform('count'))
        df_absb['dk'] = df_absb['Value'] * df_absb['share']
        df_absb = df_absb[['REG_imp','PROD_COMM','dk']].copy()

